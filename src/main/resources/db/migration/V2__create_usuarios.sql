CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo TEXT NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    user_role VARCHAR(16) NOT NULL,
    account_status VARCHAR(16) NOT NULL,
    fecha_creacion TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reset_token_hash VARCHAR(255),
    reset_token_expiry TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_role_valido CHECK (user_role IN ('ADMIN', 'USER')),
    CONSTRAINT ck_usuarios_account_status_valido CHECK (account_status IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_usuarios_reset_token_pair CHECK (
        (reset_token_hash IS NULL AND reset_token_expiry IS NULL)
        OR (reset_token_hash IS NOT NULL AND reset_token_expiry IS NOT NULL)
    )
);

CREATE INDEX idx_usuarios_user_role_account_status ON usuarios (user_role, account_status);
CREATE INDEX idx_usuarios_fecha_creacion ON usuarios (fecha_creacion);
