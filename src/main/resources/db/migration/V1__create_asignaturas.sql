CREATE TABLE asignaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    nombre_completo VARCHAR(200) NOT NULL,
    descripcion TEXT,
    area_conocimiento VARCHAR(120),
    carrera VARCHAR(120),
    numero_creditos INTEGER NOT NULL,
    contenido_tematico TEXT,
    semestre INTEGER NOT NULL,
    profesor VARCHAR(160),
    CONSTRAINT ck_asignaturas_numero_creditos_positivo CHECK (numero_creditos > 0),
    CONSTRAINT ck_asignaturas_semestre_positivo CHECK (semestre > 0)
);

CREATE INDEX idx_asignaturas_semestre ON asignaturas (semestre);
CREATE INDEX idx_asignaturas_numero_creditos ON asignaturas (numero_creditos);
